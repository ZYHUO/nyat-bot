-- 为什么需要这条 migration：school_overrides 建表以来**一行都没有**，而
-- SCHOOL_SCHEDULE_ENABLED 在生产是 true。后果不是"没有节假日感知"，而是**反向**的：
-- resolveProfile() 对 holiday 才返回暑假日计划，其余日子按周几推。于是
--   · 2026-10-01～10-07 国庆 7 天里，10/1(四) 10/2(五) 10/5(一) 10/6(二) 10/7(三)
--     全被当成"在上课"—— bot 在假期里演高中生课表
--   · 2026-10-10(六) 补班日被当成自由周末
-- 节日**提示**（"今天是中秋"）本来就有，走 beijing-time.ts 的查表；这条补的是
-- **作息/语气**那一半。
--
-- 数据来源（外部实证，不是算法推的）：
--   《国务院办公厅关于2026年部分节假日安排的通知》国办发明电〔2025〕7号
--   发文日期 2025-11-04，gov.cn 可查：
--   https://www.gov.cn/zhengce/zhengceku/202511/content_7047091.htm
--
--   一、元旦：1月1日（周四）至3日（周六）放假调休，共3天。1月4日（周日）上班。
