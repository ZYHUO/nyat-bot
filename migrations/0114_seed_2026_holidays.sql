--   三、清明节：4月4日（周六）至6日（周一）放假，共3天。
--   四、劳动节：5月1日（周五）至5日（周二）放假调休，共5天。5月9日（周六）上班。
--   五、端午节：6月19日（周五）至21日（周日）放假，共3天。
--   六、中秋节：9月25日（周五）至27日（周日）放假，共3天。
--   七、国庆节：10月1日（周四）至7日（周三）放假调休，共7天。9月20日（周日）、10月10日（周六）上班。
--
-- ⚠️ makeup_dow 的诚实说明：通知只说"X 日上班"，**没说补的是哪个星期几的课**。
-- 代码只用它来选当天的课表（school-state.ts: effectiveDow），所以填错只影响
-- "补课那天上什么课"的措辞，不影响"这是上课日不是周末"这个主判断。
-- 这里按流传最广的解释填（9/20 与 10/10 补 10/6、10/7 即周二/周三的班，取周二），
-- 其余补班日没有对应解释的填 1（周一）当占位——它只需要非 NULL。
-- 2027 年的安排要等国办 2026 年 11 月左右发文后另起 migration 补，别照抄今年。

